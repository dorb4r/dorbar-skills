#!/usr/bin/env python3
"""Write raw/_sources.md: one row per source in raw/, built from each file's provenance header.

    python -I _tools/raw_index.py [RAW]

RAW defaults to raw/ beside the folder that holds _tools/. A source is a .md or .txt file in RAW
not named _* or CONTEXT.md. Its provenance is the YAML block at the top (title, url, kind,
author, fetched, via, rights). A source with no url, fetched or rights fails, since provenance
recorded later is provenance guessed. Videos that _fetch-log.tsv says were not fetched get a
row too, so the gap shows. Rerun after adding sources; never edit _sources.md by hand.
Standard library only. Exit 1 if any source lacks provenance.
"""
import json
import re
import sys
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

REQUIRED = ("url", "fetched", "rights")


def front(text):
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    fields = {}
    for line in text[3:end if end != -1 else 0].splitlines():
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if m:
            v = m.group(2).strip()
            if len(v) > 1 and v[0] == v[-1] == '"':
                try:
                    v = json.loads(v)
                except ValueError:
                    v = v[1:-1]
            fields[m.group(1)] = str(v)
    return fields


def cell(s):
    return str(s).replace("|", "/").replace("\n", " ").strip() or "-"


def main():
    raw = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "raw"
    if not raw.is_dir():
        sys.exit(f"no such folder: {raw}")
    rows, missing, keys = [], [], set()
    for p in sorted(raw.glob("*")):
        if not p.is_file() or p.suffix.lower() not in {".md", ".txt"} or p.name.startswith(("_", ".")) \
                or p.name.lower() == "context.md":
            continue
        text = p.read_text(encoding="utf-8-sig", errors="replace")
        f = front(text)
        keys.add(p.stem)
        lacks = [k for k in REQUIRED if not f.get(k)]
        if lacks:
            missing.append(f"{p.name}: no {', '.join(lacks)}")
        words = len(re.sub(r"^---.*?\n---", "", text, flags=re.S).split())
        url = f.get("url", "")
        rows.append(f"| {cell(p.stem)} | {cell(f.get('title', p.stem))} | {cell(f.get('kind'))} | "
                    f"{cell(f'<{url}>' if url.startswith('http') else url)} | {cell(f.get('fetched'))} | "
                    f"{cell(f.get('rights'))} | {words} |")
    log = raw / "_fetch-log.tsv"
    if log.exists():
        last = {}
        for line in log.read_text(encoding="utf-8").splitlines():
            parts = line.split("\t")
            if len(parts) >= 4:
                last[parts[0]] = parts
        for vid, (_, date, status, why) in ((k, v[:4]) for k, v in sorted(last.items())):
            if vid not in keys:
                rows.append(f"| {vid} | not fetched: {status} ({why}) | youtube-transcript | "
                            f"<https://www.youtube.com/watch?v={vid}> | {date} | - | 0 |")
    lines = ["<!-- generated by _tools/raw_index.py; do not edit -->", "# Raw sources", "",
             "Untouched sources. Cite a source by its key. Never publish this folder.", "",
             "| Key | Title | Kind | URL | Fetched | Rights | Words |", "|---|---|---|---|---|---|---|", *rows]
    (raw / "_sources.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {raw.as_posix()}/_sources.md: {len(rows)} rows")
    for m in missing:
        print("  missing provenance: " + m)
    sys.exit(1 if missing else 0)


if __name__ == "__main__":
    main()
